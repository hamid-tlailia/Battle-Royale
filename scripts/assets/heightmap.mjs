// Samples a terrain scan (GLB) into a square height grid for the game map.
// usage: node heightmap.mjs <src.glb> <out.json> <size_m> <cells> [cx cz rotDeg]
import fs from 'node:fs';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
const [src, out, sizeS, cellsS, cxS = 'auto', czS = 'auto', id = 'map', vscaleS = '1'] = process.argv.slice(2);
const vscale = +vscaleS; // vertical exaggeration / compression (heights are in source units)
const size = +sizeS, cells = +cellsS, n = cells + 1;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS);
const doc = await io.read(src);
const pts = [];
for (const node of doc.getRoot().listNodes()) {
  const mesh = node.getMesh(); if (!mesh) continue;
  const m = node.getWorldMatrix();
  for (const p of mesh.listPrimitives()) {
    const a = p.getAttribute('POSITION'); const v = [0, 0, 0];
    for (let i = 0; i < a.getCount(); i++) {
      a.getElement(i, v);
      pts.push(m[0] * v[0] + m[4] * v[1] + m[8] * v[2] + m[12], m[1] * v[0] + m[5] * v[1] + m[9] * v[2] + m[13], m[2] * v[0] + m[6] * v[1] + m[10] * v[2] + m[14]);
    }
  }
}
let mn = [Infinity, Infinity, Infinity], mx = [-Infinity, -Infinity, -Infinity];
for (let i = 0; i < pts.length; i += 3) for (let k = 0; k < 3; k++) { mn[k] = Math.min(mn[k], pts[i + k]); mx[k] = Math.max(mx[k], pts[i + k]); }
const cx = cxS === 'auto' ? (mn[0] + mx[0]) / 2 : +cxS, cz = czS === 'auto' ? (mn[2] + mx[2]) / 2 : +czS;
const sum = new Float64Array(n * n), cnt = new Uint32Array(n * n);
const cell = size / cells;
for (let i = 0; i < pts.length; i += 3) {
  const ix = Math.round((pts[i] - cx + size / 2) / cell), iz = Math.round((pts[i + 2] - cz + size / 2) / cell);
  if (ix < 0 || iz < 0 || ix >= n || iz >= n) continue;
  sum[iz * n + ix] += pts[i + 1]; cnt[iz * n + ix]++;
}
const h = new Float32Array(n * n);
let filled = 0;
for (let i = 0; i < n * n; i++) if (cnt[i]) { h[i] = sum[i] / cnt[i]; filled++; } else h[i] = NaN;
// fill holes from neighbours (repeat)
for (let pass = 0; pass < 200; pass++) {
  let left = 0;
  for (let iz = 0; iz < n; iz++) for (let ix = 0; ix < n; ix++) {
    const i = iz * n + ix; if (!Number.isNaN(h[i])) continue;
    let s = 0, c = 0;
    for (const [dx, dz] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) { const x = ix + dx, z = iz + dz; if (x >= 0 && z >= 0 && x < n && z < n && !Number.isNaN(h[z * n + x])) { s += h[z * n + x]; c++; } }
    if (c) h[i] = s / c; else left++;
  }
  if (!left) break;
}
// light smoothing (scan noise) and re-base so the lowest point is 0
const sm = new Float32Array(n * n);
for (let iz = 0; iz < n; iz++) for (let ix = 0; ix < n; ix++) {
  let s = 0, c = 0;
  for (let dz = -1; dz <= 1; dz++) for (let dx = -1; dx <= 1; dx++) { const x = ix + dx, z = iz + dz; if (x >= 0 && z >= 0 && x < n && z < n) { const w = dx || dz ? 1 : 2; s += h[z * n + x] * w; c += w; } }
  sm[iz * n + ix] = s / c;
}
let lo = Infinity, hi = -Infinity; for (const v of sm) { lo = Math.min(lo, v); hi = Math.max(hi, v); }
for (let i = 0; i < sm.length; i++) sm[i] = (sm[i] - lo) * vscale;
hi = lo + (hi - lo) * vscale;
// coverage mask: 1 where the scan has data, blurred so the edge blends into generated terrain
let mask = new Float32Array(n * n); for (let i = 0; i < n * n; i++) mask[i] = cnt[i] ? 1 : 0;
for (let pass = 0; pass < 6; pass++) {
  const m2 = new Float32Array(n * n);
  for (let iz = 0; iz < n; iz++) for (let ix = 0; ix < n; ix++) {
    let s = 0, c = 0;
    for (let dz = -1; dz <= 1; dz++) for (let dx = -1; dx <= 1; dx++) { const x = ix + dx, z = iz + dz; if (x >= 0 && z >= 0 && x < n && z < n) { s += mask[z * n + x]; c++; } }
    m2[iz * n + ix] = Math.min(mask[iz * n + ix], s / c); // erode+blur: only fade inward from holes
  }
  mask = m2;
}
const hb = Buffer.alloc(n * n * 2), mb = Buffer.alloc(n * n);
for (let i = 0; i < n * n; i++) { hb.writeUInt16LE(Math.round(sm[i] * 100), i * 2); mb[i] = Math.round(mask[i] * 255); }
if (out.endsWith('.ts')) {
  fs.writeFileSync(out, `// generated by scripts/assets/heightmap.mjs from a terrain scan (see CREDITS.md)\nexport const ${id.toUpperCase()}_GRID = { cells: ${cells}, size: ${size}, range: ${(hi - lo).toFixed(2)}, heights: '${hb.toString('base64')}', mask: '${mb.toString('base64')}' };\n`);
} else fs.writeFileSync(out, JSON.stringify({ size, cells, cx, cz, range: hi - lo, heights: Array.from(sm, (v) => Math.round(v * 100) / 100) }));
console.log('points', pts.length / 3, 'bounds', mn.map((v) => v.toFixed(1)), mx.map((v) => v.toFixed(1)), 'filled', (filled / (n * n) * 100).toFixed(1) + '%', 'range', (hi - lo).toFixed(1), 'centre', cx.toFixed(1), cz.toFixed(1));
