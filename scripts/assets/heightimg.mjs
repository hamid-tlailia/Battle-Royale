// Height grid from a top-down "height render" of a scan (assets-src/tools/ortho.html?mode=height):
// R,G = 16-bit height between ymin..ymax, alpha = coverage. Output: shared/src/map/data/<id>.ts
// usage: node heightimg.mjs <height.png> <out.ts> <id> <cells> <ymin> <ymax> <vscale>
import fs from 'node:fs';
import sharp from 'sharp';
const [png, out, id, cellsS, yminS, ymaxS, vsS = '1'] = process.argv.slice(2);
const cells = +cellsS, n = cells + 1, ymin = +yminS, ymax = +ymaxS, vs = +vsS;
const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
const W = info.width, H = info.height;
const h = new Float32Array(n * n), mask = new Float32Array(n * n);
for (let iz = 0; iz < n; iz++) for (let ix = 0; ix < n; ix++) {
  // average a small pixel window around the grid vertex
  const cx = (ix / cells) * (W - 1), cy = (iz / cells) * (H - 1), r = Math.max(1, Math.floor(W / cells / 2));
  let s = 0, c = 0, a = 0, t = 0;
  for (let y = Math.max(0, Math.round(cy) - r); y <= Math.min(H - 1, Math.round(cy) + r); y++) for (let x = Math.max(0, Math.round(cx) - r); x <= Math.min(W - 1, Math.round(cx) + r); x++) {
    const i = (y * W + x) * 4; t++;
    if (data[i + 3] < 128) continue;
    s += (data[i] * 256 + data[i + 1]) / 65535 * (ymax - ymin) + ymin; c++; a++;
  }
  h[iz * n + ix] = c ? s / c : NaN; mask[iz * n + ix] = a / t;
}
for (let pass = 0; pass < 300; pass++) { let left = 0; for (let i = 0; i < n * n; i++) { if (!Number.isNaN(h[i])) continue; const ix = i % n, iz = (i / n) | 0; let s = 0, c = 0;
  for (const [dx, dz] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) { const x = ix + dx, z = iz + dz; if (x >= 0 && z >= 0 && x < n && z < n && !Number.isNaN(h[z * n + x])) { s += h[z * n + x]; c++; } }
  if (c) h[i] = s / c; else left++; } if (!left) break; }
let lo = Infinity, hi = -Infinity; for (const v of h) { lo = Math.min(lo, v); hi = Math.max(hi, v); }
const hb = Buffer.alloc(n * n * 2), mb = Buffer.alloc(n * n);
for (let i = 0; i < n * n; i++) { hb.writeUInt16LE(Math.round((h[i] - lo) * vs * 100), i * 2); mb[i] = Math.round(Math.min(1, mask[i]) * 255); }
fs.writeFileSync(out, `// generated by scripts/assets/heightimg.mjs from a terrain scan (see CREDITS.md)\nexport const ${id.toUpperCase()}_GRID = { cells: ${cells}, size: 440, range: ${((hi - lo) * vs).toFixed(2)}, base: ${lo.toFixed(3)}, vscale: ${vs}, heights: '${hb.toString('base64')}', mask: '${mb.toString('base64')}' };\n`);
let cov = 0; for (const m of mask) cov += m; console.log('grid', n, 'range', ((hi - lo) * vs).toFixed(1), 'coverage', (cov / (n * n) * 100).toFixed(1) + '%', 'base', lo.toFixed(2));
